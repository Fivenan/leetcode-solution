// Command instrument adds source-line snapshots without rewriting algorithm expressions.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
)

func main() {
	input := flag.String("input", "", "original snippet")
	output := flag.String("output", "", "generated Go file")
	pkg := flag.String("package", "solution", "generated package name")
	dir := flag.String("dir", "", "batch input directory (0001.go through 0100.go)")
	out := flag.String("out", "generated", "batch output directory")
	flag.Parse()
	var err error
	if *dir != "" {
		for id := 1; id <= 100; id++ {
			name := fmt.Sprintf("p%04d", id)
			err = generate(filepath.Join(*dir, fmt.Sprintf("%04d.go", id)), filepath.Join(*out, name, "solution.go"), name)
			if err != nil {
				break
			}
		}
	} else {
		err = generate(*input, *output, *pkg)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(input, output, pkg string) error {
	src, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("read input: %w", err)
	}
	result, err := instrument(src, pkg)
	if err != nil {
		return fmt.Errorf("instrument %s: %w", input, err)
	}
	if err = os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	return os.WriteFile(output, result, 0644)
}

type instrumenter struct{ fset *token.FileSet }
type scope map[string]bool

func copyScope(s scope) scope {
	c := scope{}
	for k := range s {
		c[k] = true
	}
	return c
}
func addName(s scope, name string) {
	if name != "" && name != "_" {
		s[name] = true
	}
}
func fields(s scope, f *ast.FieldList) {
	if f != nil {
		for _, field := range f.List {
			for _, name := range field.Names {
				addName(s, name.Name)
			}
		}
	}
}
func declarations(s scope, statement ast.Stmt) {
	switch n := statement.(type) {
	case *ast.AssignStmt:
		if n.Tok == token.DEFINE {
			for _, lhs := range n.Lhs {
				if id, ok := lhs.(*ast.Ident); ok {
					addName(s, id.Name)
				}
			}
		}
	case *ast.DeclStmt:
		if d, ok := n.Decl.(*ast.GenDecl); ok && d.Tok == token.VAR {
			for _, spec := range d.Specs {
				for _, name := range spec.(*ast.ValueSpec).Names {
					addName(s, name.Name)
				}
			}
		}
	}
}
func instrument(src []byte, pkg string) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "original.go", "package "+pkg+"\n"+string(src), parser.ParseComments)
	if err != nil {
		return nil, err
	}
	i := instrumenter{fset}
	for _, decl := range file.Decls {
		if f, ok := decl.(*ast.FuncDecl); ok && f.Body != nil {
			s := scope{}
			fields(s, f.Recv)
			fields(s, f.Type.Params)
			fields(s, f.Type.Results)
			i.block(f.Body, s, f.Name.Name)
		}
	}
	imp := &ast.GenDecl{Tok: token.IMPORT, Specs: []ast.Spec{&ast.ImportSpec{Name: ast.NewIdent("__trace"), Path: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote("leetcode.explorer/internal/trace")}}}}
	file.Decls = append([]ast.Decl{imp}, file.Decls...)
	var b bytes.Buffer
	if err := format.Node(&b, fset, file); err != nil {
		return nil, err
	}
	return append([]byte("// Code generated by cmd/instrument from the original algorithm; DO NOT EDIT.\n"), b.Bytes()...), nil
}
func (i instrumenter) step(pos token.Pos, name string, s scope) ast.Stmt {
	names := make([]string, 0, len(s))
	for k := range s {
		names = append(names, k)
	}
	sort.Strings(names)
	values := make([]ast.Expr, 0, len(names))
	for _, key := range names {
		values = append(values, &ast.KeyValueExpr{Key: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(key)}, Value: ast.NewIdent(key)})
	}
	return &ast.ExprStmt{X: &ast.CallExpr{Fun: &ast.SelectorExpr{X: ast.NewIdent("__trace"), Sel: ast.NewIdent("Step")}, Args: []ast.Expr{&ast.BasicLit{Kind: token.INT, Value: strconv.Itoa(i.fset.Position(pos).Line - 1)}, &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(name)}, &ast.CompositeLit{Type: &ast.MapType{Key: ast.NewIdent("string"), Value: &ast.InterfaceType{Methods: &ast.FieldList{}}}, Elts: values}}}}
}

// Closures inherit the variables visible at the expression, then add their own parameters.
func (i instrumenter) closures(node ast.Node, s scope, name string) {
	ast.Inspect(node, func(n ast.Node) bool {
		if n == nil {
			return false
		}
		if f, ok := n.(*ast.FuncLit); ok {
			inner := copyScope(s)
			fields(inner, f.Type.Params)
			fields(inner, f.Type.Results)
			i.block(f.Body, inner, name+".closure")
			return false
		}
		if _, ok := n.(*ast.BlockStmt); ok {
			return false
		}
		return true
	})
}
func (i instrumenter) block(b *ast.BlockStmt, s scope, name string) {
	if b != nil {
		b.List = i.statements(b.List, copyScope(s), name)
		if len(b.List) == 0 {
			b.List = []ast.Stmt{i.step(b.Lbrace, name, s)}
		}
	}
}
func (i instrumenter) statements(list []ast.Stmt, s scope, name string) []ast.Stmt {
	result := make([]ast.Stmt, 0, len(list)*2)
	for _, statement := range list {
		result = append(result, i.step(statement.Pos(), name, s))
		i.closures(statement, s, name)
		switch n := statement.(type) {
		case *ast.BlockStmt:
			i.block(n, s, name)
		case *ast.IfStmt:
			inner := copyScope(s)
			declarations(inner, n.Init)
			i.block(n.Body, inner, name)
			if n.Else != nil {
				if b, ok := n.Else.(*ast.BlockStmt); ok {
					i.block(b, inner, name)
				} else {
					processed := i.statements([]ast.Stmt{n.Else}, inner, name)
					n.Else = &ast.BlockStmt{List: processed}
				}
			}
		case *ast.ForStmt:
			inner := copyScope(s)
			declarations(inner, n.Init)
			i.block(n.Body, inner, name)
		case *ast.RangeStmt:
			inner := copyScope(s)
			if n.Tok == token.DEFINE {
				for _, v := range []ast.Expr{n.Key, n.Value} {
					if id, ok := v.(*ast.Ident); ok {
						addName(inner, id.Name)
					}
				}
			}
			i.block(n.Body, inner, name)
		case *ast.SwitchStmt:
			inner := copyScope(s)
			declarations(inner, n.Init)
			for _, c := range n.Body.List {
				clause := c.(*ast.CaseClause)
				clause.Body = i.statements(clause.Body, copyScope(inner), name)
			}
		}
		result = append(result, statement)
		declarations(s, statement)
	}
	return result
}
