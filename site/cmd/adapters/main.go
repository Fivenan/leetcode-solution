// Command adapters generates typed JSON entry points for the isolated judge snippets.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	catalogBytes, err := os.ReadFile("catalog.json")
	if err != nil {
		return err
	}
	var catalog []struct {
		ID     int `json:"id"`
		Params []struct {
			Name string `json:"name"`
		} `json:"params"`
	}
	if err = json.Unmarshal(catalogBytes, &catalog); err != nil {
		return err
	}
	if len(catalog) != 100 {
		return fmt.Errorf("catalog must contain exactly 100 problems")
	}
	registry := "// Code generated by cmd/adapters; DO NOT EDIT.\npackage generated\nimport (\"encoding/json\";\"fmt\"\n"
	for id := 1; id <= 100; id++ {
		registry += fmt.Sprintf("p%04d \"leetcode.explorer/generated/p%04d\"\n", id, id)
	}
	registry += ")\nfunc Run(id int,args []json.RawMessage)(any,error){switch id {\n"
	for id := 1; id <= 100; id++ {
		source, err := os.ReadFile(fmt.Sprintf("../go/%04d.go", id))
		if err != nil {
			return err
		}
		f, err := parser.ParseFile(token.NewFileSet(), "solution.go", append([]byte("package solution\n"), source...), 0)
		if err != nil {
			return err
		}
		var fn *ast.FuncDecl
		for _, d := range f.Decls {
			if v, ok := d.(*ast.FuncDecl); ok && v.Recv == nil {
				fn = v
				break
			}
		}
		if fn == nil {
			return fmt.Errorf("%d: no function", id)
		}
		body := fmt.Sprintf("// Code generated by cmd/adapters; DO NOT EDIT.\npackage p%04d\nimport (\"encoding/json\";\"leetcode.explorer/internal/input\")\n", id)
		if bytes.Contains(source, []byte("ListNode")) {
			body += "type ListNode = input.ListNode\n"
		}
		if bytes.Contains(source, []byte("TreeNode")) {
			body += "type TreeNode = input.TreeNode\n"
		}
		body += "func Run(args []json.RawMessage)(any,error){\n"
		count := 0
		for _, p := range fn.Type.Params.List {
			count += len(p.Names)
		}
		if catalog[id-1].ID != id || len(catalog[id-1].Params) != count {
			return fmt.Errorf("problem %d: catalog signature does not match source", id)
		}
		body += fmt.Sprintf("if err:=input.Validate(%d,args,%d);err!=nil{return nil,err}\n", id, count)
		var names []string
		for _, p := range fn.Type.Params.List {
			var b bytes.Buffer
			format.Node(&b, token.NewFileSet(), p.Type)
			typ := b.String()
			parse := map[string]string{"int": "Int", "float64": "Float", "string": "String", "[]int": "Ints", "[]string": "Strings", "[][]int": "Matrix", "[][]byte": "Board", "*ListNode": "List", "[]*ListNode": "Lists", "*TreeNode": "Tree"}[typ]
			if parse == "" {
				return fmt.Errorf("%d unsupported %s", id, typ)
			}
			for range p.Names {
				name := fmt.Sprintf("a%d", len(names))
				body += fmt.Sprintf("%s,err:=input.%s(args[%d]);if err!=nil{return nil,err}\n", name, parse, len(names))
				names = append(names, name)
			}
		}
		call := fn.Name.Name + "(" + strings.Join(names, ",") + ")"
		if id == 26 || id == 27 || id == 80 {
			body += "k:=" + call + "\nreturn map[string]any{\"length\":k,\"nums\":a0[:k]},nil\n"
		} else if fn.Type.Results == nil {
			body += call + "\nreturn input.Output(a0),nil\n"
		} else {
			body += "return input.Output(" + call + "),nil\n"
		}
		body += "}\n"
		dir := fmt.Sprintf("generated/p%04d", id)
		if err = os.MkdirAll(dir, 0755); err != nil {
			return err
		}
		if err = writeGo(filepath.Join(dir, "adapter.go"), body); err != nil {
			return err
		}
		registry += fmt.Sprintf("case %d:return p%04d.Run(args)\n", id, id)
	}
	registry += "default:return nil,fmt.Errorf(\"unknown problem %d\",id)}}\n"
	return writeGo("generated/registry.go", registry)
}

func writeGo(path, source string) error {
	b, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return os.WriteFile(path, b, 0644)
}
